import Foundation

/// Finds rebuildable build output and dependency folders inside code projects
/// (`node_modules`, Cargo `target`, SwiftPM `.build`, `.next`, `Pods`, …).
///
/// A folder only counts when its project has the marker file that produces it
/// (for example `node_modules` next to `package.json`). Inside Git repositories,
/// folders with tracked files are never offered, and folders Git does not ignore
/// are only offered for review. Projects touched recently are left unselected.
public enum ProjectArtifactScanner {
    public struct Kind: Sendable {
        public let name: String
        public let title: String
        /// Files next to the folder that prove it was generated by a build tool.
        public let markers: [String]
        /// Files inside the folder that prove it (used by Python virtualenvs).
        public let innerMarkers: [String]
        /// Generated without doubt, so it can be preselected even outside Git.
        public let certain: Bool

        init(_ name: String, _ title: String, markers: [String] = [], inner: [String] = [], certain: Bool) {
            self.name = name
            self.title = title
            self.markers = markers
            self.innerMarkers = inner
            self.certain = certain
        }
    }

    static let gradle = ["build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"]

    public static let kinds: [Kind] = [
        Kind("node_modules", "Node.js dependencies", markers: ["package.json"], certain: true),
        Kind(".next", "Next.js build", markers: ["package.json"], certain: true),
        Kind(".nuxt", "Nuxt build", markers: ["package.json"], certain: true),
        Kind(".svelte-kit", "SvelteKit build", markers: ["package.json"], certain: true),
        Kind(".turbo", "Turborepo cache", markers: ["package.json", "turbo.json"], certain: true),
        Kind(".parcel-cache", "Parcel cache", markers: ["package.json"], certain: true),
        Kind(".angular", "Angular cache", markers: ["angular.json", "package.json"], certain: true),
        Kind("target", "Rust build output", markers: ["Cargo.toml"], certain: true),
        Kind("target", "Maven build output", markers: ["pom.xml", "build.sbt"], certain: false),
        Kind(".build", "Swift package build", markers: ["Package.swift"], certain: true),
        Kind("Pods", "CocoaPods dependencies", markers: ["Podfile"], certain: true),
        Kind(".gradle", "Gradle cache", markers: gradle, certain: true),
        Kind("build", "Gradle build output", markers: gradle, certain: true),
        Kind(".dart_tool", "Dart tool cache", markers: ["pubspec.yaml"], certain: true),
        Kind("build", "Flutter build output", markers: ["pubspec.yaml"], certain: true),
        Kind(".zig-cache", "Zig cache", markers: ["build.zig"], certain: true),
        Kind("zig-cache", "Zig cache", markers: ["build.zig"], certain: true),
        Kind("zig-out", "Zig build output", markers: ["build.zig"], certain: false),
        Kind("elm-stuff", "Elm packages", markers: ["elm.json"], certain: true),
        Kind("build", "Build output", markers: ["package.json", "CMakeLists.txt", "pyproject.toml", "setup.py"], certain: false),
        Kind("dist", "Distribution build", markers: ["package.json", "pyproject.toml", "setup.py"], certain: false),
        Kind("vendor", "Composer dependencies", markers: ["composer.json"], certain: false),
        Kind(".venv", "Python virtual environment", inner: ["pyvenv.cfg"], certain: false),
        Kind("venv", "Python virtual environment", inner: ["pyvenv.cfg"], certain: false),
    ]

    static let names: Set<String> = Set(kinds.map(\.name))

    /// Folders under the home folder where code usually lives. Missing ones are skipped.
    public static func defaultRoots(home: URL = FileManager.default.homeDirectoryForCurrentUser) -> [URL] {
        let candidates = [
            "Projects", "projects", "Developer", "Code", "code", "src", "dev", "Dev",
            "Work", "work", "workspace", "Workspace", "repos", "Repos", "git",
            "GitHub", "Github", "Sites", "www",
            "Documents/GitHub", "Documents/Projects", "Documents/Code",
            "Desktop", "Documents",
        ]
        return candidates.map { home.appendingPathComponent($0, isDirectory: true) }
    }

    public static func scan(
        home: URL = FileManager.default.homeDirectoryForCurrentUser,
        roots: [URL]? = nil,
        recentDays: Int = 7,
        minBytes: Int64 = 0,
        maxDepth: Int = 8,
        git: String? = GitProbe.executable,
        fileManager: FileManager = .default,
        progress: ((_ folder: String, _ found: Int) -> Void)? = nil,
        isCancelled: () -> Bool = { false }
    ) -> [Artifact] {
        let recentCutoff = Date().addingTimeInterval(-Double(max(0, recentDays)) * 86_400)
        var visited = Set<FileIdentity>()
        var results: [Artifact] = []
        var stack: [(URL, Int)] = []

        // Visit roots in order, skipping missing ones and aliases of folders already
        // queued (APFS is case-insensitive, so ~/Code and ~/code are one folder).
        for root in (roots ?? defaultRoots(home: home)).reversed() {
            stack.append((root.standardizedFileURL, 0))
        }

        let keys: [URLResourceKey] = [.isDirectoryKey, .isSymbolicLinkKey, .isPackageKey]
        while let (dir, depth) = stack.popLast() {
            if isCancelled() { break }
            guard let identity = FileIdentity(path: dir.path, fileManager: fileManager),
                  visited.insert(identity).inserted else { continue }
            progress?(dir.path, results.count)

            guard let entries = try? fileManager.contentsOfDirectory(
                at: dir,
                includingPropertiesForKeys: keys,
                options: []
            ) else { continue }

            let siblings = Set(entries.map(\.lastPathComponent))
            var children: [URL] = []

            for entry in entries {
                guard let values = try? entry.resourceValues(forKeys: Set(keys)),
                      values.isDirectory == true,
                      values.isSymbolicLink != true else { continue }
                let name = entry.lastPathComponent

                if names.contains(name),
                   let kind = match(name: name, folder: entry, siblings: siblings, fileManager: fileManager) {
                    if let artifact = evaluate(
                        folder: entry, project: dir, kind: kind, siblings: siblings,
                        recentCutoff: recentCutoff, minBytes: minBytes, git: git,
                        fileManager: fileManager
                    ) {
                        results.append(artifact)
                    }
                    continue  // never descend into build output
                }

                if name.hasPrefix(".") || name == "Library" || values.isPackage == true { continue }
                if depth + 1 <= maxDepth { children.append(entry) }
            }

            for child in children.reversed() { stack.append((child, depth + 1)) }
        }

        return results.sorted { $0.bytes > $1.bytes }
    }

    static func match(name: String, folder: URL, siblings: Set<String>, fileManager: FileManager) -> Kind? {
        kinds.first { kind in
            guard kind.name == name else { return false }
            if !kind.markers.isEmpty, !kind.markers.contains(where: siblings.contains) { return false }
            if !kind.innerMarkers.isEmpty {
                return kind.innerMarkers.contains {
                    fileManager.fileExists(atPath: folder.appendingPathComponent($0).path)
                }
            }
            return true
        }
    }

    static func evaluate(
        folder: URL,
        project: URL,
        kind: Kind,
        siblings: Set<String>,
        recentCutoff: Date,
        minBytes: Int64,
        git: String?,
        fileManager: FileManager
    ) -> Artifact? {
        // A repository of its own nested in the project is someone's work, not output.
        if fileManager.fileExists(atPath: folder.appendingPathComponent(".git").path) { return nil }

        var notes: [String] = []
        var preselect = kind.certain

        if let repo = GitProbe.repositoryRoot(containing: project, fileManager: fileManager) {
            if let git {
                switch GitProbe.status(of: folder, in: project, git: git) {
                case .tracked:
                    return nil
                case .ignored:
                    // Virtualenvs can hold packages installed by hand, so they stay for review.
                    preselect = kind.innerMarkers.isEmpty
                    notes.append("ignored by Git")
                case .untracked:
                    preselect = false
                    notes.append("not in .gitignore")
                case .unknown:
                    preselect = false
                    notes.append("Git check failed")
                }
            } else {
                preselect = false
                notes.append("in Git repo \(repo.lastPathComponent); Git not installed to check")
            }
        }

        let lastActive = activity(folder: folder, project: project, kind: kind, siblings: siblings, fileManager: fileManager)
        if let lastActive, lastActive > recentCutoff {
            preselect = false
            notes.append("recently active")
        }

        guard let artifact = ArtifactBuilder.make(
            path: folder.path,
            allowedRoot: project.path,
            group: kind.title,
            detail: ([project.lastPathComponent] + notes).joined(separator: " · "),
            risk: preselect ? .safe : .caution,
            autoselect: preselect,
            fileManager: fileManager
        ), artifact.bytes >= minBytes else { return nil }

        return Artifact(
            path: artifact.path,
            bytes: artifact.bytes,
            files: artifact.files,
            group: artifact.group,
            detail: artifact.detail,
            risk: artifact.risk,
            autoselect: artifact.autoselect,
            allowedRoot: artifact.allowedRoot,
            isDirectory: artifact.isDirectory,
            modified: lastActive ?? artifact.modified,
            device: artifact.device,
            inode: artifact.inode
        )
    }

    /// The newest modification time of the folder itself and the project's marker files.
    static func activity(folder: URL, project: URL, kind: Kind, siblings: Set<String>, fileManager: FileManager) -> Date? {
        var paths = [folder.path]
        paths += kind.markers.filter(siblings.contains).map { project.appendingPathComponent($0).path }
        return paths
            .compactMap { (try? fileManager.attributesOfItem(atPath: $0))?[.modificationDate] as? Date }
            .max()
    }
}

struct FileIdentity: Hashable {
    let device: UInt64
    let inode: UInt64

    init?(path: String, fileManager: FileManager) {
        guard let attributes = try? fileManager.attributesOfItem(atPath: path),
              let device = (attributes[.systemNumber] as? NSNumber)?.uint64Value,
              let inode = (attributes[.systemFileNumber] as? NSNumber)?.uint64Value else { return nil }
        self.device = device
        self.inode = inode
    }
}

public enum GitProbe {
    public enum Status: Equatable { case tracked, ignored, untracked, unknown }

    /// A usable `git`, without triggering the Command Line Tools install prompt that
    /// `/usr/bin/git` shows when no developer directory is set up.
    public static let executable: String? = {
        let fm = FileManager.default
        for path in ["/opt/homebrew/bin/git", "/usr/local/bin/git"] where fm.isExecutableFile(atPath: path) {
            return path
        }
        let selected = ProcessRunner.run("/usr/bin/xcode-select", ["-p"], timeout: 5)
        let developer = selected.stdout.trimmingCharacters(in: .whitespacesAndNewlines)
        if selected.status == 0, !developer.isEmpty, fm.fileExists(atPath: developer) {
            return "/usr/bin/git"
        }
        return nil
    }()

    static func repositoryRoot(containing dir: URL, fileManager: FileManager) -> URL? {
        var current = dir.standardizedFileURL
        while current.path != "/" {
            if fileManager.fileExists(atPath: current.appendingPathComponent(".git").path) { return current }
            current.deleteLastPathComponent()
        }
        return nil
    }

    static func status(of folder: URL, in project: URL, git: String) -> Status {
        let tracked = ProcessRunner.run(git, ["-C", folder.path, "ls-files", "-z", "--", "."], timeout: 20)
        guard tracked.status == 0, !tracked.timedOut else { return .unknown }
        if !tracked.stdout.isEmpty { return .tracked }

        let ignored = ProcessRunner.run(
            git, ["-C", project.path, "check-ignore", "-q", "--", folder.lastPathComponent + "/"], timeout: 10
        )
        switch ignored.status {
        case 0: return .ignored
        case 1: return .untracked
        default: return .unknown
        }
    }
}
